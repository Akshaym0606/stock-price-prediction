# ============================================================
# STOCK DATA COLLECTION & PREPROCESSING
# ============================================================

import warnings
warnings.filterwarnings("ignore")

import numpy as np
import pandas as pd
import yfinance as yf
import ta

print("=" * 60)
print("STOCK DATA COLLECTION & PREPROCESSING")
print("=" * 60)

# ============================================================
# STEP 1 : DOWNLOAD STOCK DATA
# ============================================================

print("\n[1/5] Downloading stock data from Yahoo Finance...")

ticker = "AAPL"

df = yf.download(
    ticker,
    start="2020-01-01",
    # ✅ CHANGE 1: No 'end' date — downloads up to the latest available date
    progress=False,
    auto_adjust=False
)

# Check whether data was downloaded
if df.empty:
    raise ValueError(
        "No data downloaded. Check your internet connection or ticker symbol."
    )

# Flatten MultiIndex columns if needed
if isinstance(df.columns, pd.MultiIndex):
    df.columns = df.columns.get_level_values(0)

print(f"✓ {ticker}: {len(df)} rows downloaded")
print("Columns:", list(df.columns))
print(f"Date Range: {df.index[0].date()} --> {df.index[-1].date()}")

# ============================================================
# STEP 2 : HANDLE MISSING VALUES
# ============================================================

print("\n[2/5] Handling Missing Values...")

missing_before = df.isnull().sum().sum()

df.dropna(inplace=True)

missing_after = df.isnull().sum().sum()

print("Missing Before :", missing_before)
print("Missing After  :", missing_after)
print("Rows Remaining :", len(df))

# ============================================================
# STEP 3 : CREATE TECHNICAL INDICATORS
# ============================================================

print("\n[3/5] Creating Technical Indicators...")

close = df["Close"]
high = df["High"]
low = df["Low"]
volume = df["Volume"]

# Moving Averages
df["MA_10"] = close.rolling(10).mean()
df["MA_20"] = close.rolling(20).mean()
df["MA_50"] = close.rolling(50).mean()

print("✓ Moving Averages")

# RSI
df["RSI"] = ta.momentum.RSIIndicator(
    close=close,
    window=14
).rsi()

print("✓ RSI")

# MACD
macd = ta.trend.MACD(close=close)

df["MACD"] = macd.macd()
df["MACD_Signal"] = macd.macd_signal()
df["MACD_Hist"] = macd.macd_diff()

print("✓ MACD")

# Bollinger Bands
bb = ta.volatility.BollingerBands(
    close=close,
    window=20
)

df["BB_Upper"] = bb.bollinger_hband()
df["BB_Middle"] = bb.bollinger_mavg()
df["BB_Lower"] = bb.bollinger_lband()

print("✓ Bollinger Bands")

# ATR
atr = ta.volatility.AverageTrueRange(
    high=high,
    low=low,
    close=close,
    window=14
)

df["ATR"] = atr.average_true_range()

print("✓ ATR")

# Volume Moving Average
df["Volume_MA"] = volume.rolling(10).mean()

print("✓ Volume Moving Average")

# ============================================================
# STEP 4 : FEATURE ENGINEERING
# ============================================================

print("\n[4/5] Feature Engineering...")

df["Daily_Return"] = close.pct_change()

df["Log_Return"] = np.log(close / close.shift(1))

df["Price_Range"] = high - low

df["Close_Above_MA"] = (
    close > df["MA_20"]
).astype(int)

# ✅ CHANGE 2: Target is next day's closing price (continuous) for
#    forecasting models (ARIMA, Prophet, LSTM) — not a binary 0/1 class
df["Target"] = close.shift(-1)

print("✓ Daily Return")
print("✓ Log Return")
print("✓ Price Range")
print("✓ Close Above MA")
print("✓ Target Variable (Next Day Close Price)")

# Remove NaN rows generated by rolling calculations and target shift
df.dropna(inplace=True)

print(f"Final Dataset Shape : {df.shape}")

# ============================================================
# STEP 5 : SAVE DATA
# ============================================================

print("\n[5/5] Saving Files...")

processed_file = "stock_data_processed.csv"
summary_file = "stock_data_summary.csv"

df.to_csv(processed_file)

df.describe().round(4).to_csv(summary_file)

print(f"✓ Saved : {processed_file}")
print(f"✓ Saved : {summary_file}")

# ============================================================
# FINAL REPORT
# ============================================================

print("\n" + "=" * 60)
print("PREPROCESSING COMPLETED SUCCESSFULLY")
print("=" * 60)

print(f"Total Samples  : {len(df)}")
print(f"Total Features : {len(df.columns)}")

print(
    f"Date Range : {df.index[0].date()} --> {df.index[-1].date()}"
)

print("\nFeatures:")

for i, col in enumerate(df.columns, 1):
    print(f"{i:2d}. {col}")

print("\nFirst Five Rows:\n")
print(df.head())

print("\nDataset Info:\n")
print(df.info())

print("\nAll preprocessing completed successfully.")
print("Hand over 'stock_data_processed.csv' to the Model Training team.")
